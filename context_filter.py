if __name__ == "__main__":
    # Пример 1: корректное употребление (должно засчитаться)
    text1 = "Красота русской природы восхищает каждого путешественника."
    print(f"Пример 1: '{text1}'")
    print(f"  Валидных вхождений 'красота': {count_valid_markers(text1, 'красота')}")
    # Ожидаемый результат: 1
    
    # Пример 2: ироничное употребление (должно быть отсеяно)
    text2 = "Ну, красота, ничего не скажешь — опять всё сломалось."
    print(f"\nПример 2: '{text2}'")
    print(f"  Валидных вхождений 'красота': {count_valid_markers(text2, 'красота')}")
    # Ожидаемый результат: 0
    
    # Пример 3: отрицание (должно быть отсеяно)
    text3 = "Никакой красоты в этом решении я не вижу."
    print(f"\nПример 3: '{text3}'")
    print(f"  Валидных вхождений 'красота': {count_valid_markers(text3, 'красота')}")
    # Ожидаемый результат: 0
    
    # Пример 4: множественные вхождения (одно корректное, одно ироничное)
    text4 = "Красота древних храмов вдохновляет. Ну а тут — красота, ничего не скажешь."
    print(f"\nПример 4: '{text4}'")
    checks = check_context_window(text4, 'красота')
    print(f"  Результат по каждому вхождению: {checks}")
    print(f"  Всего валидных: {count_valid_markers(text4, 'красота')}")
    # Ожидаемый результат: [True, False], всего 1
