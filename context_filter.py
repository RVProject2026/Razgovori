"""
context_filter.py
Модуль контекстной верификации ценностных маркеров.
Реализует правило контекстного окна (±5 слов) для отсева:
- ироничных и отрицательных употреблений (пример: "Ну, красота, ничего не скажешь")
- нецелевых частей речи (например, "красота" как междометие)
- омонимов, утративших ценностную нагрузку в данном контексте

Используется в расчёте ИЦЛП и ИКАН для повышения точности алгоритма.
"""

import re
import pymorphy2

# Инициализация морфологического анализатора
morph = pymorphy2.MorphAnalyzer()

# Словари маркеров, искажающих ценностное значение
NEGATION_MARKERS = {
    'не', 'ни', 'никакой', 'никакая', 'никакое', 'никакие',
    'нет', 'без', 'отнюдь', 'вовсе', 'далеко'
}

IRONY_MARKERS = {
    'ну', 'якобы', 'так называемый', 'скажешь тоже', 'как бы',
    'ничего не скажешь', 'не чего сказать', 'тоже мне'
}

# Размер контекстного окна (±5 токенов)
WINDOW_SIZE = 5


def tokenize(text):
    """Разбивает текст на токены (слова в нижнем регистре)."""
    return re.findall(r'\b[а-яёa-z]+\b', text.lower())


def check_context_window(text, target_lemma, window_size=WINDOW_SIZE):
    """
    Проверяет контекстное окно ±window_size слов вокруг каждого вхождения
    целевой леммы в тексте.
    
    Возвращает список булевых значений (по одному на каждое вхождение):
    - True  = вхождение корректно, засчитывается в N_цен
    - False = вхождение исключается (ирония, отрицание, нецелевая часть речи)
    
    Параметры:
        text (str): анализируемый текст
        target_lemma (str): целевая лемма из словаря (например, 'красота')
        window_size (int): размер окна в токенах (по умолчанию 5)
    """
    tokens = tokenize(text)
    results = []
    
    for i, token in enumerate(tokens):
        if token == target_lemma.lower():
            # 1. Морфологический фильтр
            # Получаем разбор слова в данном контексте
            parses = morph.parse(token)
            if parses:
                pos_tag = parses[0].tag.POS
                # Если слово функционирует как междометие или частица — отсекаем
                if pos_tag in ('INTJ', 'PRCL'):  # INTJ=междометие, PRCL=частица
                    results.append(False)
                    continue
            
            # 2. Лексический фильтр модификаторов
            # Определяем границы окна
            start = max(0, i - window_size)
            end = min(len(tokens), i + window_size + 1)
            window = tokens[start:end]
            
            # Проверяем наличие маркеров отрицания/иронии в окне
            has_negation = any(w in NEGATION_MARKERS for w in window)
            has_irony = any(w in IRONY_MARKERS for w in window)
            
            if has_negation or has_irony:
                results.append(False)
                continue
            
            # Если оба фильтра пройдены — вхождение корректно
            results.append(True)
    
    return results


def count_valid_markers(text, target_lemma, window_size=WINDOW_SIZE):
    """
    Возвращает количество корректных (валидных) вхождений целевой леммы
    в тексте после применения контекстного фильтра.
    """
    checks = check_context_window(text, target_lemma, window_size)
    return sum(1 for c in checks if c)


